import pool from '../config/db';
import type { GoalRow } from '../types/goal.types';
import type { CreateGoalDto, UpdateGoalDto } from '../types/goal.types';

// ---------------------------------------------------------------------------
// Select all active goals for a customer
// ---------------------------------------------------------------------------
export async function findGoalsByCustomerId(customerId: string): Promise<GoalRow[]> {
  const result = await pool.query<GoalRow>(
    `SELECT goal_id, customer_id, goal_type, goal_name,
            target_amount, current_funded_amount, target_date, priority,
            is_active, created_by, modified_by, created_at, modified_at
       FROM goals
      WHERE customer_id = $1
        AND is_active = TRUE
      ORDER BY priority DESC, target_date ASC`,
    [customerId],
  );
  return result.rows;
}

// ---------------------------------------------------------------------------
// Select a single active goal by ID (across all customers)
// ---------------------------------------------------------------------------
export async function findActiveGoalById(goalId: string): Promise<GoalRow | undefined> {
  const result = await pool.query<GoalRow>(
    `SELECT goal_id, customer_id, goal_type, goal_name,
            target_amount, current_funded_amount, target_date, priority,
            is_active, created_by, modified_by, created_at, modified_at
       FROM goals
      WHERE goal_id = $1
        AND is_active = TRUE
      LIMIT 1`,
    [goalId],
  );
  return result.rows[0];
}

// ---------------------------------------------------------------------------
// Insert a new goal — ID generated by goal_id_seq via column DEFAULT
// ---------------------------------------------------------------------------
export async function insertGoal(
  customerId: string,
  dto: CreateGoalDto,
  userId: string,
): Promise<GoalRow> {
  const result = await pool.query<GoalRow>(
    `INSERT INTO goals
       (customer_id, goal_type, goal_name, target_amount,
        current_funded_amount, target_date, priority,
        created_by, modified_by)
     VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $8)
     RETURNING goal_id, customer_id, goal_type, goal_name,
               target_amount, current_funded_amount, target_date, priority,
               is_active, created_by, modified_by, created_at, modified_at`,
    [
      customerId,
      dto.goal_type,
      dto.goal_name,
      dto.target_amount,
      dto.current_funded_amount,
      dto.target_date,
      dto.priority,
      userId,
    ],
  );
  // INSERT INTO a table with a DEFAULT expression always returns exactly one row
  return result.rows[0] as GoalRow;
}

// ---------------------------------------------------------------------------
// Partial update — only provided fields are SET; always updates audit columns
// ---------------------------------------------------------------------------
export async function updateGoal(
  goalId: string,
  dto: UpdateGoalDto,
  userId: string,
): Promise<GoalRow | undefined> {
  const setClauses: string[] = [
    'modified_at = NOW()',
    'modified_by = $1',
  ];
  const params: unknown[] = [userId, goalId];

  if (dto.goal_type !== undefined) {
    params.push(dto.goal_type);
    setClauses.push(`goal_type = $${params.length}`);
  }
  if (dto.goal_name !== undefined) {
    params.push(dto.goal_name);
    setClauses.push(`goal_name = $${params.length}`);
  }
  if (dto.target_amount !== undefined) {
    params.push(dto.target_amount);
    setClauses.push(`target_amount = $${params.length}`);
  }
  if (dto.current_funded_amount !== undefined) {
    params.push(dto.current_funded_amount);
    setClauses.push(`current_funded_amount = $${params.length}`);
  }
  if (dto.target_date !== undefined) {
    params.push(dto.target_date);
    setClauses.push(`target_date = $${params.length}`);
  }
  if (dto.priority !== undefined) {
    params.push(dto.priority);
    setClauses.push(`priority = $${params.length}`);
  }

  const sql = `
    UPDATE goals
       SET ${setClauses.join(', ')}
     WHERE goal_id = $2
       AND is_active = TRUE
     RETURNING goal_id, customer_id, goal_type, goal_name,
               target_amount, current_funded_amount, target_date, priority,
               is_active, created_by, modified_by, created_at, modified_at
  `;

  const result = await pool.query<GoalRow>(sql, params);
  return result.rows[0];
}
